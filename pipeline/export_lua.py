"""Pack build/circuit.json into Lua source files the mod can load.

Layout produced under mod/fly_brain/:
    net_csr.lua    base64 blobs: CSR indptr / indices / weights
    net_meta.lua   sensory map, motor read-out groups, type index for debugging

Encoding
    indptr   uint32 LE, n+1 entries (1-based, points into indices/weights)
    indices  uint16 LE, nnz entries (1-based postsynaptic neuron id)
    weights  int16  LE, nnz entries, in units of 0.02 mV

int16 at 0.02 mV covers the full weight range (max |w| = 389 mV) with a worst
case error of 0.01 mV -- 0.14% of the 7 mV distance from rest to threshold.
"""
from __future__ import annotations

import argparse
import base64
import json
import struct
from pathlib import Path

import numpy as np
import scipy.sparse as sp

from netio import Circuit, ROOT

W_SCALE = 0.02  # mV per int16 unit
OUT = ROOT / "mod/fly_brain"


# Isaac's script loader silently returns nil for a large .lua file: a single
# 459 KB net_csr.lua never executed, while the mod's 30 KB files load fine.  So
# the connectome is split across many small part files, each well under that,
# with short lines too.  Base64 contains no quote or escape characters, so the
# chunks need no escaping.
PART_BYTES = 24000
LINE_CHARS = 1024


def b64_parts(raw: bytes) -> list[str]:
    """Base64 of `raw`, split into part-sized blocks of short string literals."""
    s = base64.b64encode(raw).decode("ascii")
    lines = [s[i : i + LINE_CHARS] for i in range(0, len(s), LINE_CHARS)]
    per_part = max(1, PART_BYTES // LINE_CHARS)
    return ["\n".join(f'  "{ln}",' for ln in lines[i : i + per_part])
            for i in range(0, len(lines), per_part)]


def prune(W: sp.csr_matrix, thr_mV: float) -> sp.csr_matrix:
    if thr_mV <= 0:
        return W
    W = W.copy()
    W.data[np.abs(W.data) < thr_mV] = 0.0
    W.eliminate_zeros()
    return W


def write_csr(W: sp.csr_matrix, path: Path, meta: dict):
    n = W.shape[0]
    assert n < 65536, "uint16 neuron ids require fewer than 65536 neurons"
    indptr = (W.indptr + 1).astype("<u4")           # 1-based
    indices = (W.indices + 1).astype("<u2")         # 1-based
    q = np.round(W.data / W_SCALE).astype("<i2")

    fields = {"indptr": indptr, "indices": indices, "weights": q}
    manifest: dict[str, list[str]] = {}
    total = 0

    for field, arr in fields.items():
        parts = b64_parts(arr.tobytes())
        names = []
        for k, chunk in enumerate(parts, 1):
            name = f"net_{field}_{k}"
            names.append(name)
            part = (
                "-- Generated by pipeline/export_lua.py -- do not edit by hand.\n"
                f"-- {field} part {k} of {len(parts)}, base64.\n"
                "FlyBrainPart = FlyBrainPart or {}\n"
                f'FlyBrainPart["{name}"] = {{\n{chunk}\n}}\n'
                f'return FlyBrainPart["{name}"]\n'
            )
            p = path.parent / f"{name}.lua"
            p.write_text(part, encoding="ascii")
            total += len(part)
        manifest[field] = names

    def lua_names(names):
        return "{ " + ", ".join(f'"{n}"' for n in names) + " }"

    body = f"""-- Generated by pipeline/export_lua.py -- do not edit by hand.
-- {meta['source']}
-- {n} neurons, {W.nnz} synaptic connections, weights in units of {W_SCALE} mV.
--
-- The arrays live in the net_*_N.lua part files listed below rather than here:
-- Isaac's script loader silently fails on a large .lua file, so every part is
-- kept small.  Loader.load() includes them and concatenates.
FlyBrainNetCSR = {{
  n = {n},
  nnz = {W.nnz},
  wscale = {W_SCALE},
  parts = {{
    indptr  = {lua_names(manifest['indptr'])},
    indices = {lua_names(manifest['indices'])},
    weights = {lua_names(manifest['weights'])},
  }},
}}
return FlyBrainNetCSR
"""
    path.write_text(body, encoding="ascii")
    return len(body) + total, sum(len(v) for v in manifest.values())


def write_bias(path: Path, bias: np.ndarray, k: float):
    """Per-neuron resting potential, as a plain Lua array.

    Only 2053 numbers, so no packing is needed.  The values are clamped so the
    resting potential stays at least 2 mV below the -45 mV spike threshold: a
    neuron must never fire without input, which is the property the whole model
    rests on and which tools/bench.lua asserts.
    """
    from lif import V_0, V_TH

    vrest = V_0 + bias * k
    ceiling = V_TH - 2.0
    clipped = int((vrest > ceiling).sum())
    vrest = np.minimum(vrest, ceiling)

    rows = []
    for i in range(0, len(vrest), 12):
        rows.append("  " + ", ".join(f"{x:.4f}" for x in vrest[i : i + 12]))
    body = (
        "-- Generated by pipeline/export_lua.py -- do not edit by hand.\n"
        "-- Per-neuron resting potential in mV: -52 plus k * the measured mean\n"
        f"-- effect of the synaptic input this truncated circuit lost (k = {k}).\n"
        "-- See pipeline/compute_bias.py and docs/METHODS.md.\n"
        "FlyBrainNetVrest = {\n" + ",\n".join(rows) + ",\n}\nreturn FlyBrainNetVrest\n"
    )
    path.write_text(body, encoding="ascii")
    return len(body), clipped


def lua_list(xs, per_line=20, fmt="{}"):
    xs = list(xs)
    rows = []
    for i in range(0, len(xs), per_line):
        rows.append(", ".join(fmt.format(x) for x in xs[i : i + per_line]))
    return "\n    " + ",\n    ".join(rows) + "\n  " if rows else ""


def write_meta(c: Circuit, path: Path):
    """Sensory map + motor read-out groups, as plain Lua tables."""
    sensory_roles = {
        "looming": "loom",
        "small_object": "object",
        "bar": "bar",
        "optic_flow": "flow",
        "landmark": "landmark",
    }

    groups: dict[str, list] = {}
    for kind in sensory_roles.values():
        groups[kind] = []
    for i in range(c.N):
        k = sensory_roles.get(c.role[i])
        if k is None:
            continue
        side = 1 if c.side[i] == "right" else -1
        groups[k].append((i + 1, round(float(c.az[i]), 1), round(float(c.el[i]), 3), side, c.type[i]))

    parts = ["-- Generated by pipeline/export_lua.py -- do not edit by hand.",
             "-- Sensory neurons carry a head-centred azimuth in degrees (negative = left)",
             "-- and a normalised elevation in [-1, 1] (+1 = dorsal visual field), derived",
             "-- from their retinotopic position in the optic lobe.",
             "FlyBrainNetMeta = {", "  sensory = {"]
    # Packed several per line and without per-neuron comments: this file has to
    # stay small, because Isaac's loader gives up on large scripts.
    for kind, rows in groups.items():
        types = sorted({ct for *_, ct in rows})
        parts.append(f"    -- {kind}: {', '.join(types)}")
        parts.append(f"    {kind} = {{")
        cells = [f"{{{i},{az},{el},{side}}}" for i, az, el, side, _ in rows]
        for j in range(0, len(cells), 6):
            parts.append("      " + ",".join(cells[j : j + 6]) + ",")
        parts.append("    },")
    parts.append("  },")

    # --- motor read-out -----------------------------------------------------
    def ids_of(types, side=None):
        out = []
        for i in range(c.N):
            if c.type[i] in types and (side is None or c.side[i] == side):
                out.append(i + 1)
        return out

    steer = {"DNa02", "DNa01", "DNa03"}
    escape = {"DNp09", "DNp01", "DNp10", "DNp11", "DNp06", "DNp04", "DNp35", "DNp103"}
    forward = {"DNb01", "DNb02", "DNa04", "DNg13"}

    dn_left = [i + 1 for i in range(c.N) if c.role[i] == "descending" and c.side[i] == "left"]
    dn_right = [i + 1 for i in range(c.N) if c.role[i] == "descending" and c.side[i] == "right"]

    motor = {
        "steer_left": ids_of(steer, "left"),
        "steer_right": ids_of(steer, "right"),
        "escape": ids_of(escape),
        "escape_left": [i for i in ids_of(escape, "left")],
        "escape_right": [i for i in ids_of(escape, "right")],
        "forward": ids_of(forward),
        "dn_left": dn_left,
        "dn_right": dn_right,
        "pfl3_left": ids_of({"PFL3"}, "left"),
        "pfl3_right": ids_of({"PFL3"}, "right"),
    }
    parts.append("  motor = {")
    for k, v in motor.items():
        parts.append(f"    {k} = {{{', '.join(str(x) for x in v)}}},")
    parts.append("  },")

    # --- named populations, for the debug overlay ---------------------------
    watch = ["EPG", "PEN_a(PEN1)", "PEN_b(PEN2)", "Delta7", "PFL3", "PFL2",
             "LC4", "LPLC2", "LC6", "LC11", "TuBu01a", "ER1", "ER4d"]
    parts.append("  watch = {")
    for t in watch:
        ids = [i + 1 for i in range(c.N) if c.type[i] == t]
        if ids:
            parts.append(f'    ["{t}"] = {{{", ".join(str(x) for x in ids)}}},')
    parts.append("  },")

    # EPG neurons with their side, so the mod can read out the compass bump
    epg = [(i + 1, 1 if c.side[i] == "right" else -1) for i in range(c.N) if c.type[i] == "EPG"]
    parts.append("  epg = {" + ", ".join(f"{{{i},{s}}}" for i, s in epg) + "},")
    parts.append(f"  n = {c.N},")
    parts.append("}")
    parts.append("return FlyBrainNetMeta")
    body = "\n".join(parts) + "\n"
    path.write_text(body, encoding="ascii")
    return len(body), {k: len(v) for k, v in motor.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--prune", type=float, default=0.55,
                    help="drop |w| below this many mV (0.55 = 2 synapse-equivalents)")
    args = ap.parse_args()

    c = Circuit()
    W = prune(c.W, args.prune)
    print(f"pruned |w| < {args.prune} mV: {c.W.nnz} -> {W.nnz} edges "
          f"({100 * W.nnz / c.W.nnz:.1f}% kept, "
          f"{100 * abs(W).sum() / abs(c.W).sum():.2f}% of synaptic mass)")

    OUT.mkdir(parents=True, exist_ok=True)
    for stale in OUT.glob("net_ind*_*.lua"):
        stale.unlink()
    for stale in OUT.glob("net_weights_*.lua"):
        stale.unlink()
    size, nparts = write_csr(W, OUT / "net_csr.lua", c.meta)
    print(f"  net_csr.lua + {nparts} part files, {size / 1024:.0f} KB total")
    size, motor = write_meta(c, OUT / "net_meta.lua")
    print(f"  net_meta.lua  {size / 1024:.0f} KB")
    print("  motor groups:", motor)

    bias_path = ROOT / "build/bias.npy"
    fit_path = ROOT / "build/bias_fit.json"
    if bias_path.exists():
        bias = np.load(bias_path)
        k = json.loads(fit_path.read_text())["k"] if fit_path.exists() else 0.75
        size, clipped = write_bias(OUT / "net_vrest.lua", bias, k)
        print(f"  net_vrest.lua {size / 1024:.0f} KB  (k = {k}, "
              f"{clipped} neurons clamped below threshold)")
    else:
        print("  (no build/bias.npy; run compute_bias.py for the truncation correction)")

    # also save the pruned matrix for the validation harness
    sp.save_npz(ROOT / "build/W_pruned.npz", W.tocsr())


if __name__ == "__main__":
    main()
